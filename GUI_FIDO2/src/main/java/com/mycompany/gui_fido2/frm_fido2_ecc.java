    private void btn_loginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_loginActionPerformed
        try {
        String challenge = txt_challenge.getText().trim();
        String signature = txt_signature.getText().trim();

        if (challenge.isEmpty() || signature.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Vui lòng bấm 'Tạo Challenge' trước khi đăng nhập!");
            return;
        }

        // Server dùng Public Key kiểm tra xem chữ ký có khớp với Challenge không
        boolean isValid = fido2.verifyAssertion(challenge, signature);

        if (isValid) {
            JOptionPane.showMessageDialog(this, 
                "XÁC THỰC FIDO2 THÀNH CÔNG!\nChữ ký số ECC hợp lệ. Đăng nhập thành công!", 
                "Thành công", 
                JOptionPane.INFORMATION_MESSAGE);
        } else {
            JOptionPane.showMessageDialog(this, 
                "XÁC THỰC THẤT BẠI!\nChữ ký không hợp lệ.", 
                "Lỗi xác thực", 
                JOptionPane.ERROR_MESSAGE);
        }

    } catch (Exception ex) {
        JOptionPane.showMessageDialog(this, "Lỗi khi xác thực: " + ex.getMessage(), "Lỗi", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btn_loginActionPerformed

