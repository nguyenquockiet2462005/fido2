    private void btn_registerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_registerActionPerformed
        try {
        String username = txt_username.getText().trim();
        if (username.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập Username trước khi đăng ký!");
            return;
        }

        fido2.registerFIDO2Token();
        txt_publickey.setText(fido2.getPublicKeyBase64());

        JOptionPane.showMessageDialog(this, 
            "Đăng ký thiết bị FIDO2 thành công!\nPublic Key đã được lưu trên Server.", 
            "Thông báo", 
            JOptionPane.INFORMATION_MESSAGE);

    } catch (Exception ex) {
        JOptionPane.showMessageDialog(this, "Lỗi khi đăng ký: " + ex.getMessage(), "Lỗi", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btn_registerActionPerformed

    private void btn_challengeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_challengeActionPerformed
        try {
        if (!fido2.isRegistered()) {
            JOptionPane.showMessageDialog(this, 
                "Cảnh báo: Bạn chưa đăng ký! Vui lòng bấm 'Đăng ký' trước.", 
                "Lỗi chưa đăng ký", 
                JOptionPane.WARNING_MESSAGE);
            return;
        }

        // 1. Xóa chữ ký cũ nếu có
        txt_signature.setText("");

        // 2. Tạo và hiển thị Challenge lên giao diện
        String challenge = fido2.generateServerChallenge();
        txt_challenge.setText(challenge);

        // 3. Tạo ô nhập mật khẩu hiển thị dấu sao '*'
        javax.swing.JPasswordField pf = new javax.swing.JPasswordField();
        pf.setEchoChar('*');

        int option = JOptionPane.showConfirmDialog(
            this, 
            pf, 
            "Xác thực FIDO2: Nhập mã PIN thiết bị", 
            JOptionPane.OK_CANCEL_OPTION, 
            JOptionPane.QUESTION_MESSAGE
        );

        // 4. Kiểm tra phản hồi người dùng
        if (option == JOptionPane.OK_OPTION) {
            String userPin = new String(pf.getPassword());

            if (userPin.equals("123456")) {
                // Nhập đúng PIN -> Tự động tạo chữ ký số
                String signature = fido2.signChallenge(challenge);
                txt_signature.setText(signature);
            } else {
                JOptionPane.showMessageDialog(
                    this, 
                    "Xác thực PIN thất bại! Mã PIN không đúng.", 
                    "Lỗi PIN", 
                    JOptionPane.ERROR_MESSAGE
                );
            }
        } else {
            JOptionPane.showMessageDialog(this, "Đã hủy xác thực! Chữ ký chưa được tạo.");
        }

    } catch (Exception ex) {
        JOptionPane.showMessageDialog(this, "Lỗi: " + ex.getMessage(), "Lỗi", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btn_challengeActionPerformed

